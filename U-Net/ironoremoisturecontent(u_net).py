class DoubleConv(nn.Module):
    """Helper block containing Two 3x3 Convolutions with Padding"""
    def __init__(self, in_channels, out_channels):
        super().__init__()
        self.conv = nn.Sequential(
            nn.Conv2d(in_channels, out_channels, kernel_size=3, padding=1),
            nn.BatchNorm2d(out_channels), nn.ReLU(inplace=True),
            nn.Conv2d(out_channels, out_channels, kernel_size=3, padding=1),
            nn.BatchNorm2d(out_channels), nn.ReLU(inplace=True)
        )
    def forward(self, x): return self.conv(x)

class UShapedClassifier(nn.Module):
    def __init__(self, num_classes=7):
        super().__init__()

        # --- 3 ENCODERS (Downsampling) ---
        self.enc1 = DoubleConv(3, 64)
        self.pool1 = nn.MaxPool2d(2)

        self.enc2 = DoubleConv(64, 128)
        self.pool2 = nn.MaxPool2d(2)

        self.enc3 = DoubleConv(128, 256)
        self.pool3 = nn.MaxPool2d(2)

        # --- BOTTLENECK ---
        self.bottleneck = DoubleConv(256, 512)

        # --- 3 DECODERS (Upsampling + Skip Connections) ---
        self.up1 = nn.ConvTranspose2d(512, 256, kernel_size=2, stride=2)
        self.dec1 = DoubleConv(512, 256) # 256 (upsampled) + 256 (skip)

        self.up2 = nn.ConvTranspose2d(256, 128, kernel_size=2, stride=2)
        self.dec2 = DoubleConv(256, 128) # 128 (upsampled) + 128 (skip)

        self.up3 = nn.ConvTranspose2d(128, 64, kernel_size=2, stride=2)
        self.dec3 = DoubleConv(128, 64)  # 64 (upsampled) + 64 (skip)

        # --- FEATURE PROJECTION & CLASSIFICATION ---
        # Compress the final high-res 64-channel 224x224 image into a dense vector
        self.feature_proj = nn.Sequential(
            nn.Conv2d(64, 512, kernel_size=3, padding=1),
            nn.BatchNorm2d(512), nn.ReLU(inplace=True),
            nn.AdaptiveAvgPool2d((1, 1)),
            nn.Flatten()
        )

        # Classifier (512 U-Shape features + 256 MLBP features = 768)
        self.classifier = nn.Sequential(
            nn.Linear(768, 512), nn.BatchNorm1d(512), nn.ReLU(inplace=True), nn.Dropout(0.4), nn.Linear(512, num_classes)
        )

    def forward(self, img, mlbp):
        # Encoders Path
        e1 = self.enc1(img)            # [B, 64, 224, 224]
        e2 = self.enc2(self.pool1(e1)) # [B, 128, 112, 112]
        e3 = self.enc3(self.pool2(e2)) # [B, 256, 56, 56]

        # Bottleneck
        b = self.bottleneck(self.pool3(e3)) # [B, 512, 28, 28]

        # Decoders Path (with skip connections)
        d1 = self.dec1(torch.cat([self.up1(b), e3], dim=1)) # [B, 256, 56, 56]
        d2 = self.dec2(torch.cat([self.up2(d1), e2], dim=1)) # [B, 128, 112, 112]
        d3 = self.dec3(torch.cat([self.up3(d2), e1], dim=1)) # [B, 64, 224, 224]

        # Global Feature Pooling
        u_features = self.feature_proj(d3)

        # Fuse and Classify
        return self.classifier(torch.cat([u_features, mlbp], dim=1))

