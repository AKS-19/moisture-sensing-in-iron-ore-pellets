import time, torch, cv2, numpy as np
from PIL import Image
from torchvision import transforms

def benchmark_unet(iterations=100):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"[INFO] Benchmarking U-Shaped Classifier on: {device.type.upper()}")

    if not os.path.exists('best_unet_model.pt'):
        print("[ERROR] 'best_unet_model.pt' not found."); return

    model = UShapedClassifier(len(CLASSES)).to(device)
    model.load_state_dict(torch.load('best_unet_model.pt', map_location=device, weights_only=True))
    model.eval()

    tf = transforms.Compose([transforms.Resize((224, 224)), transforms.ToTensor(), transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])])
    dummy_image = Image.fromarray(np.random.randint(0, 255, (224, 224, 3), dtype=np.uint8))

    print("[INFO] Warming up GPU (10 passes)...")
    for _ in range(10):
        i_tensor = tf(dummy_image).unsqueeze(0).to(device)
        i_cv = cv2.resize(cv2.cvtColor(np.array(dummy_image), cv2.COLOR_RGB2GRAY), (224, 224))
        m_tensor = torch.tensor(compute_mlbp(i_cv), dtype=torch.float32).unsqueeze(0).to(device)
        with torch.no_grad(): _ = model(i_tensor, m_tensor)

    print(f"[INFO] Running {iterations} passes through 3 Encoders / 3 Decoders...\n")

    pipeline_times = []
    with torch.no_grad():
        for _ in range(iterations):
            if device.type == 'cuda': torch.cuda.synchronize()
            t_start = time.perf_counter()

            i_t = tf(dummy_image).unsqueeze(0).to(device)
            i_c = cv2.resize(cv2.cvtColor(np.array(dummy_image), cv2.COLOR_RGB2GRAY), (224, 224))
            m_t = torch.tensor(compute_mlbp(i_c), dtype=torch.float32).unsqueeze(0).to(device)
            _ = model(i_t, m_t)

            if device.type == 'cuda': torch.cuda.synchronize()
            pipeline_times.append((time.perf_counter() - t_start) * 1000)

    avg_pipe_time = np.mean(pipeline_times)

    print("="*60)
    print("         U-SHAPED CLASSIFIER SPEED REPORT")
    print("="*60)
    print(f"Full Pipeline Latency : {avg_pipe_time:.2f} ms / frame")
    print(f"Actual Production FPS : {1000/avg_pipe_time:.1f} FPS")
    print("="*60)

benchmark_unet()