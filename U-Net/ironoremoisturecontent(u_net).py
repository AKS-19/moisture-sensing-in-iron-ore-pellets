def compute_mlbp(image_cv_gray):
    h, w = image_cv_gray.shape
    mean_tau = cv2.filter2D(image_cv_gray.astype(np.float32), -1, np.ones((3, 3), np.float32) / 9.0)
    padded = np.pad(image_cv_gray.astype(np.float32), 1, mode='reflect')
    mlbp = np.zeros((h, w), dtype=np.uint8)
    dx, dy = [-1,  0,  1, 1, 1, 0, -1, -1], [-1, -1, -1, 0, 1, 1,  1,  0]
