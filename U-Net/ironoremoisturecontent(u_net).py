def prepare_dataset_hierarchy():
    if not os.path.exists(ZIP_PATH): raise ValueError(f"[ERROR] '{ZIP_PATH}' not found!")
    if os.path.exists(BASE_DIR): shutil.rmtree(BASE_DIR)
    os.makedirs(BASE_DIR)
    with zipfile.ZipFile(ZIP_PATH, 'r') as z: z.extractall(BASE_DIR)

    all_files, labels = [], []
    norm_classes = {c.lower().replace(" ", ""): c for c in CLASSES}
    for root, dirs, files in os.walk(BASE_DIR):
        p_norm = os.path.basename(root).lower().replace(" ", "")
        imgs = [f for f in files if f.lower().endswith(('.jpg', '.jpeg', '.png', '.bmp'))]
        if p_norm in norm_classes:
            all_files.extend([os.path.join(root, f) for f in imgs])
            labels.extend([norm_classes[p_norm]] * len(imgs))

    X_tr, X_temp, y_tr, y_temp = train_test_split(all_files, labels, test_size=0.30, stratify=labels, random_state=42)
    X_val, X_te, y_val, y_te = train_test_split(X_temp, y_temp, test_size=0.50, stratify=y_temp, random_state=42)

    if os.path.exists(SPLIT_DIR): shutil.rmtree(SPLIT_DIR)
    for split, paths, lbls in zip(['train', 'val', 'test'], [X_tr, X_val, X_te], [y_tr, y_val, y_te]):
        for cls in CLASSES: os.makedirs(os.path.join(SPLIT_DIR, split, cls), exist_ok=True)
        for path, cls in zip(paths, lbls): shutil.copy2(path, os.path.join(SPLIT_DIR, split, cls, os.path.basename(path)))

def compute_mlbp(image_cv_gray):
    h, w = image_cv_gray.shape
    img_float = image_cv_gray.astype(np.float32)
    mean_tau = cv2.filter2D(img_float, -1, np.ones((3, 3), np.float32) / 9.0)
    padded = np.pad(img_float, 1, mode='reflect')
    mlbp = np.zeros((h, w), dtype=np.uint8)
    dx, dy = [-1,  0,  1, 1, 1, 0, -1, -1], [-1, -1, -1, 0, 1, 1,  1,  0]
    for i in range(8):
        neighbor = padded[1+dy[i]:1+dy[i]+h, 1+dx[i]:1+dx[i]+w]
        mlbp |= ((neighbor >= mean_tau).astype(np.uint8) << i)
    hist, _ = np.histogram(mlbp.ravel(), bins=256, range=(0, 256))
    return (hist.astype(np.float32) / (hist.sum() + 1e-6))

class DualStreamDataset(Dataset):
    def __init__(self, root_dir, transform=None):
        self.root_dir, self.transform = Path(root_dir), transform
        self.paths, self.labels = [], []
        for idx, cls in enumerate(CLASSES):
            d = self.root_dir / cls
            if d.exists():
                for f in os.listdir(d):
                    if f.lower().endswith(('.jpg', '.png', '.jpeg', '.bmp')):
                        self.paths.append(str(d / f)); self.labels.append(idx)

    def __len__(self): return len(self.paths)
    def __getitem__(self, idx):
        img_pil = Image.open(self.paths[idx]).convert('RGB')
        img_tensor = self.transform(img_pil)
        img_cv = cv2.resize(cv2.cvtColor(np.array(img_pil), cv2.COLOR_RGB2GRAY), (224, 224))
        mlbp_tensor = torch.tensor(compute_mlbp(img_cv), dtype=torch.float32)
        return img_tensor, mlbp_tensor, self.labels[idx]

