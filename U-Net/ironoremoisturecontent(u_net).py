class DoubleConv(nn.Module):
    def __init__(self, in_channels, out_channels):
        super().__init__()
        self.conv = nn.Sequential(nn.Conv2d(in_channels, out_channels, 3, padding=1), nn.BatchNorm2d(out_channels), nn.ReLU(inplace=True),
                                  nn.Conv2d(out_channels, out_channels, 3, padding=1), nn.BatchNorm2d(out_channels), nn.ReLU(inplace=True))
    def forward(self, x): return self.conv(x)

class UShapedClassifier(nn.Module):
    def __init__(self, num_classes=7):
        super().__init__()
        self.enc1, self.pool1 = DoubleConv(3, 64), nn.MaxPool2d(2)
        self.enc2, self.pool2 = DoubleConv(64, 128), nn.MaxPool2d(2)
        self.enc3, self.pool3 = DoubleConv(128, 256), nn.MaxPool2d(2)
        self.bottleneck = DoubleConv(256, 512)
        self.up1, self.dec1 = nn.ConvTranspose2d(512, 256, 2, 2), DoubleConv(512, 256)
        self.up2, self.dec2 = nn.ConvTranspose2d(256, 128, 2, 2), DoubleConv(256, 128)
        self.up3, self.dec3 = nn.ConvTranspose2d(128, 64, 2, 2), DoubleConv(128, 64)
        self.feature_proj = nn.Sequential(nn.Conv2d(64, 512, 3, padding=1), nn.BatchNorm2d(512), nn.ReLU(), nn.AdaptiveAvgPool2d((1, 1)), nn.Flatten())
        self.classifier = nn.Sequential(nn.Linear(768, 512), nn.BatchNorm1d(512), nn.ReLU(), nn.Dropout(0.4), nn.Linear(512, num_classes))

    def forward(self, img, mlbp):
        e1 = self.enc1(img)
        e2 = self.enc2(self.pool1(e1))
        e3 = self.enc3(self.pool2(e2))
        b = self.bottleneck(self.pool3(e3))
        d1 = self.dec1(torch.cat([self.up1(b), e3], dim=1))
        d2 = self.dec2(torch.cat([self.up2(d1), e2], dim=1))
        d3 = self.dec3(torch.cat([self.up3(d2), e1], dim=1))
        return self.classifier(torch.cat([self.feature_proj(d3), mlbp], dim=1))

