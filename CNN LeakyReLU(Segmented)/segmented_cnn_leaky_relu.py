# 2. ARCHITECTURE: LeakyReLU CNN
# -------------------------------------------------------------------------
class QuadrantLeakyCNN(nn.Module):
    def __init__(self, num_classes=7):
        super().__init__()
        # Swapped all nn.ReLU() for nn.LeakyReLU(negative_slope=0.01)
        self.layer1 = nn.Sequential(nn.Conv2d(3, 32, 3, padding='same'), nn.BatchNorm2d(32), nn.LeakyReLU(0.01, inplace=True), nn.MaxPool2d(2))
        self.layer2 = nn.Sequential(nn.Conv2d(32, 64, 3, padding='same'), nn.BatchNorm2d(64), nn.LeakyReLU(0.01, inplace=True), nn.MaxPool2d(2))
        self.layer3 = nn.Sequential(nn.Conv2d(64, 128, 3, padding='same'), nn.BatchNorm2d(128), nn.LeakyReLU(0.01, inplace=True), nn.MaxPool2d(2))
        self.layer4 = nn.Sequential(nn.Conv2d(128, 256, 3, padding='same'), nn.BatchNorm2d(256), nn.LeakyReLU(0.01, inplace=True), nn.AdaptiveAvgPool2d((2, 2)))

        self.flatten = nn.Flatten()
        self.fc = nn.Sequential(
            nn.Linear(256 * 2 * 2, 512),
            nn.BatchNorm1d(512),
            nn.LeakyReLU(0.01, inplace=True),
            nn.Dropout(0.4),
            nn.Linear(512, num_classes)
        )

    def forward(self, x):
        return self.fc(self.flatten(self.layer4(self.layer3(self.layer2(self.layer1(x))))))

