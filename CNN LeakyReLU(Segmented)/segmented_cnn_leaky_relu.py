        plt.title(f"LeakyReLU Ensemble Prediction: {CLASSES[pred_idx.item()]}\n(Average Softmax Confidence: {conf.item() * 100:.2f}%)", color='blue', fontweight='bold')
        plt.axis('off'); plt.show()

        print("\n--- Final Ensemble Output (Average of 4 Quadrants) ---")
        for i, c in enumerate(CLASSES): print(f"{c}: {final_probs[i].item() * 100:.2f}%")

