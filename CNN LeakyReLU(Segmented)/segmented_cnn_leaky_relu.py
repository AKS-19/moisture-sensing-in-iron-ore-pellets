import time, torch, numpy as np
from PIL import Image
from torchvision import transforms
import torch.nn as nn
from torch.cuda.amp import autocast

def benchmark_leaky_cnn(iterations=500):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"[INFO] Benchmarking LeakyReLU Pipeline on: {device.type.upper()}")

    if not os.path.exists('best_leaky_cnn.pt'):
        print("[ERROR] 'best_leaky_cnn.pt' not found."); return

    model = QuadrantLeakyCNN(len(CLASSES)).to(device)
    model.load_state_dict(torch.load('best_leaky_cnn.pt', map_location=device, weights_only=True))
    model.eval()

    tf = transforms.Compose([transforms.ToTensor(), transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])])
    dummy_image = Image.fromarray(np.random.randint(0, 255, (494, 659, 3), dtype=np.uint8))

    print("[INFO] Warming up GPU...")
    for _ in range(20):
        dummy_batch = torch.randn(4, 3, 240, 328).to(device)
        with torch.no_grad():
            with autocast(): _ = model(dummy_batch)

    print(f"[INFO] Running {iterations} iterations on End-to-End Pipeline...\n")

    pipeline_times = []
    with torch.no_grad():
        for _ in range(iterations):
            if device.type == 'cuda': torch.cuda.synchronize()
            t_start = time.perf_counter()

            img_res = dummy_image.resize((656, 480))
            quads = [img_res.crop((0,0,328,240)), img_res.crop((328,0,656,240)), img_res.crop((0,240,328,480)), img_res.crop((328,240,656,480))]
            batch_tensors = torch.stack([tf(q) for q in quads]).to(device)

            with autocast():
                probs = torch.mean(nn.Softmax(dim=1)(model(batch_tensors)), dim=0)

            if device.type == 'cuda': torch.cuda.synchronize()
            pipeline_times.append((time.perf_counter() - t_start) * 1000)

    avg_pipe_time = np.mean(pipeline_times)

    print("="*60)
    print("         LEAKY-RELU CNN SPEED REPORT")
    print("="*60)
    print(f"Full Pipeline Latency : {avg_pipe_time:.2f} ms / frame")
    print(f"Actual Production FPS : {1000/avg_pipe_time:.1f} FPS")
    print("="*60)

benchmark_leaky_cnn()