        self.layer1 = nn.Sequential(nn.Conv2d(3, 64, 3, 1, 'same'), nn.BatchNorm2d(64), nn.ReLU(), nn.MaxPool2d(2))
        self.layer2 = nn.Sequential(nn.Conv2d(64, 128, 3, 1, 'same'), nn.BatchNorm2d(128), nn.ReLU(), nn.MaxPool2d(2))
