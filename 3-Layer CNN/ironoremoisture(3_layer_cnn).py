def train_and_evaluate():
    prepare_dataset_hierarchy()
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"\n[INFO] Training Enhanced Custom CNN on: {device}")

    tr_loader = DataLoader(DualStreamPelletDataset(os.path.join(SPLIT_DIR, 'train'), train_tf), batch_size=32, shuffle=True)
    val_loader = DataLoader(DualStreamPelletDataset(os.path.join(SPLIT_DIR, 'val'), test_tf), batch_size=32)
    te_loader = DataLoader(DualStreamPelletDataset(os.path.join(SPLIT_DIR, 'test'), test_tf), batch_size=32)

    model = Enhanced3LayerCNN(len(CLASSES)).to(device)
    criterion = nn.CrossEntropyLoss()
    optimizer = optim.AdamW(model.parameters(), lr=5e-4, weight_decay=1e-3)
    scheduler = optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode='min', factor=0.1, patience=3)

    best_val_loss = float('inf')
    epochs = 30

    for epoch in range(epochs):
        model.train()
        tr_loss = 0.0
        for imgs, mlbps, lbls in tr_loader:
            imgs, mlbps, lbls = imgs.to(device), mlbps.to(device), lbls.to(device)
            optimizer.zero_grad()
            loss = criterion(model(imgs, mlbps), lbls)
            loss.backward()
            optimizer.step()
            tr_loss += loss.item() * imgs.size(0)

        tr_loss /= len(tr_loader.dataset)

        model.eval()
        val_loss, all_preds, all_labels = 0.0, [], []
        with torch.no_grad():
            for imgs, mlbps, lbls in val_loader:
                imgs, mlbps, lbls = imgs.to(device), mlbps.to(device), lbls.to(device)
                out = model(imgs, mlbps)
                val_loss += criterion(out, lbls).item() * imgs.size(0)
                all_preds.extend(torch.max(out, 1)[1].cpu().numpy()); all_labels.extend(lbls.cpu().numpy())

        val_loss /= len(val_loader.dataset)
        scheduler.step(val_loss)
        print(f"Epoch [{epoch+1}/{epochs}] | Train Loss: {tr_loss:.4f} | Val Loss: {val_loss:.4f} | Val Acc: {accuracy_score(all_labels, all_preds):.4f}")

        if val_loss < best_val_loss:
            best_val_loss = val_loss
            torch.save(model.state_dict(), 'best_custom_enhanced.pt')

    print("\n[INFO] Evaluating on Test Split...")
    model.load_state_dict(torch.load('best_custom_enhanced.pt', map_location=device, weights_only=True))
    model.eval()
    all_preds, all_labels = [], []
    with torch.no_grad():
        for imgs, mlbps, lbls in te_loader:
            imgs, mlbps, lbls = imgs.to(device), mlbps.to(device), lbls.to(device)
            all_preds.extend(torch.max(model(imgs, mlbps), 1)[1].cpu().numpy()); all_labels.extend(lbls.cpu().numpy())

    print("\n--- Classification Report (Enhanced 3-Layer CNN) ---")
    print(classification_report(all_labels, all_preds, target_names=CLASSES, zero_division=0))

    plt.figure(figsize=(8, 6))
    sns.heatmap(confusion_matrix(all_labels, all_preds), annot=True, fmt='d', cmap='Blues', xticklabels=CLASSES, yticklabels=CLASSES)
    plt.title('Enhanced CNN Moisture Content - Confusion Matrix')
    plt.xlabel('Predicted Label'); plt.ylabel('True Label'); plt.tight_layout(); plt.show()

    if IN_COLAB: files.download('best_custom_enhanced.pt')

if __name__ == "__main__":
    train_and_evaluate()

