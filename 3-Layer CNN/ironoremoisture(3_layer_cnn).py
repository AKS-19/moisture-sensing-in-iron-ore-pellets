        img_tensor = tf(image_pil).unsqueeze(0).to(device)

        img_cv = cv2.resize(cv2.cvtColor(np.array(image_pil), cv2.COLOR_RGB2GRAY), (224, 224))
        mlbp_tensor = torch.tensor(compute_mlbp(img_cv), dtype=torch.float32).unsqueeze(0).to(device)

        with torch.no_grad():
            raw_logits = model(img_tensor, mlbp_tensor)

            # EXPLICIT SOFTMAX
            probabilities = nn.Softmax(dim=1)(raw_logits)[0]
            conf, pred_idx = torch.max(probabilities, 0)

        plt.figure(figsize=(6, 6))
        plt.imshow(image_pil)
        plt.title(f"Prediction: {CLASSES[pred_idx.item()]}\n(Softmax Confidence: {conf.item() * 100:.2f}%)", color='green', fontweight='bold')
        plt.axis('off'); plt.show()

        print("\n--- Final Softmax Output ---")
        for i, c in enumerate(CLASSES): print(f"{c}: {probabilities[i].item() * 100:.2f}%")

