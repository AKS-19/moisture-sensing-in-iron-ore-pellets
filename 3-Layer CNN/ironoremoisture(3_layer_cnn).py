# 2. UPGRADED 3-LAYER CNN (With Texture Fusion)
# -------------------------------------------------------------------------
class Enhanced3LayerCNN(nn.Module):
    def __init__(self, num_classes=7):
        super().__init__()

        # Layer 1: Wider filters (64)
        self.layer1 = nn.Sequential(
            nn.Conv2d(in_channels=3, out_channels=64, kernel_size=3, stride=1, padding='same'),
            nn.BatchNorm2d(64), nn.ReLU(), nn.MaxPool2d(kernel_size=2)
        )
        # Layer 2: Wider filters (128)
        self.layer2 = nn.Sequential(
            nn.Conv2d(in_channels=64, out_channels=128, kernel_size=3, stride=1, padding='same'),
            nn.BatchNorm2d(128), nn.ReLU(), nn.MaxPool2d(kernel_size=2)
        )
        # Layer 3: Wider filters (256)
        self.layer3 = nn.Sequential(
            nn.Conv2d(in_channels=128, out_channels=256, kernel_size=3, stride=1, padding='same'),
            nn.BatchNorm2d(256), nn.ReLU(),
            nn.AdaptiveAvgPool2d((2, 2)) # Captures 4x more spatial resolution than before
        )

        # Fusion Classifier (256 * 2 * 2 = 1024 CNN features) + (256 MLBP features) = 1280 Total
        self.flatten = nn.Flatten()
        self.classifier = nn.Sequential(
            nn.Linear(1024 + 256, 512),
            nn.BatchNorm1d(512),
            nn.ReLU(),
            nn.Dropout(0.4), # Added dropout to prevent overfitting
            nn.Linear(512, num_classes)
        )

    def forward(self, img, mlbp):
        # Image through 3-Layer CNN
        cnn_features = self.flatten(self.layer3(self.layer2(self.layer1(img))))
        # Fuse with MLBP
        fused = torch.cat([cnn_features, mlbp], dim=1)
        return self.classifier(fused)

