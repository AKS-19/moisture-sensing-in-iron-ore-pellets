def benchmark_inference_b5(iterations=100):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"[INFO] Benchmarking EfficientNet-B5 on: {device.type.upper()}")

    if not os.path.exists('best_effnet_b5.pt'):
        print("[ERROR] 'best_effnet_b5.pt' not found."); return

    # Relies on the model architecture defined in Cell 2
    model = EfficientNetB5FusionNet(num_classes=len(CLASSES)).to(device)
    model.load_state_dict(torch.load('best_effnet_b5.pt', map_location=device, weights_only=True))
    model.eval()

    transform = transforms.Compose([transforms.Resize((224, 224)), transforms.ToTensor(), transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])])
    dummy_image = Image.fromarray(np.random.randint(0, 255, (300, 300, 3), dtype=np.uint8))

    print("[INFO] Warming up GPU (10 passes)...")
    for _ in range(10):
        i_tensor = transform(dummy_image).unsqueeze(0).to(device)
        i_cv = cv2.resize(cv2.cvtColor(np.array(dummy_image), cv2.COLOR_RGB2GRAY), (224, 224))
        m_tensor = torch.tensor(compute_mlbp(i_cv), dtype=torch.float32).unsqueeze(0).to(device)
        with torch.no_grad(): _ = model(i_tensor, m_tensor)

    print(f"[INFO] Warm-up complete. Running {iterations} iterations...\n")

    # TEST 1: Pure GPU AI Bound
    i_tensor = transform(dummy_image).unsqueeze(0).to(device)
    i_cv = cv2.resize(cv2.cvtColor(np.array(dummy_image), cv2.COLOR_RGB2GRAY), (224, 224))
    m_tensor = torch.tensor(compute_mlbp(i_cv), dtype=torch.float32).unsqueeze(0).to(device)

    model_times = []
    with torch.no_grad():
        for _ in range(iterations):
            if device.type == 'cuda': torch.cuda.synchronize()
            t_start = time.perf_counter()
            _ = model(i_tensor, m_tensor)
            if device.type == 'cuda': torch.cuda.synchronize()
            model_times.append((time.perf_counter() - t_start) * 1000)

    avg_model_time = np.mean(model_times)

    # TEST 2: CPU + GPU End-to-End Pipeline
    pipeline_times = []
    with torch.no_grad():
        for _ in range(iterations):
            if device.type == 'cuda': torch.cuda.synchronize()
            t_start = time.perf_counter()

            i_t = transform(dummy_image).unsqueeze(0).to(device)
            i_c = cv2.resize(cv2.cvtColor(np.array(dummy_image), cv2.COLOR_RGB2GRAY), (224, 224))
            m_t = torch.tensor(compute_mlbp(i_c), dtype=torch.float32).unsqueeze(0).to(device)
            _ = model(i_t, m_t)

            if device.type == 'cuda': torch.cuda.synchronize()
            pipeline_times.append((time.perf_counter() - t_start) * 1000)

    avg_pipe_time = np.mean(pipeline_times)

    print("="*60)
    print("         EFFICIENTNET-B5 INFERENCE SPEED REPORT")
    print("="*60)
    print(f"1. Pure AI Model Latency : {avg_model_time:.2f} ms / frame")
    print(f"   Max Theoretical Speed : {1000/avg_model_time:.1f} FPS")
    print("-" * 60)
    print(f"2. Full Pipeline Latency : {avg_pipe_time:.2f} ms / frame")
    print("   (Includes Image Prep + MLBP CPU Math + AI Forward Pass)")
    print(f"   Actual Production FPS : {1000/avg_pipe_time:.1f} FPS")
    print("="*60)

benchmark_inference_b5()