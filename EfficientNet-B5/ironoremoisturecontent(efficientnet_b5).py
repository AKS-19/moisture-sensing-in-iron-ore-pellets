CLASSES = ['10gm', '30gm', '40gm', '50gm', '60gm', '70gm', '80gm']

def compute_mlbp(image_cv_gray):
    h, w = image_cv_gray.shape
    img_float = image_cv_gray.astype(np.float32)
    mean_tau = cv2.filter2D(img_float, -1, np.ones((3, 3), np.float32) / 9.0)
    padded = np.pad(img_float, 1, mode='reflect')
    mlbp = np.zeros((h, w), dtype=np.uint8)
    dx, dy = [-1,  0,  1, 1, 1, 0, -1, -1], [-1, -1, -1, 0, 1, 1,  1,  0]
    for i in range(8):
        neighbor = padded[1+dy[i]:1+dy[i]+h, 1+dx[i]:1+dx[i]+w]
        mlbp |= ((neighbor >= mean_tau).astype(np.uint8) << i)
    hist, _ = np.histogram(mlbp.ravel(), bins=256, range=(0, 256))
    return hist.astype(np.float32) / (hist.sum() + 1e-6)

class ChannelAttention(nn.Module):
    def __init__(self, in_planes, ratio=16):
        super().__init__()
        self.avg_pool, self.max_pool = nn.AdaptiveAvgPool2d(1), nn.AdaptiveMaxPool2d(1)
        self.mlp = nn.Sequential(nn.Conv2d(in_planes, in_planes // ratio, 1, bias=False), nn.ReLU(), nn.Conv2d(in_planes // ratio, in_planes, 1, bias=False))
        self.sigmoid = nn.Sigmoid()
    def forward(self, x): return self.sigmoid(self.mlp(self.avg_pool(x)) + self.mlp(self.max_pool(x)))

class SpatialAttention(nn.Module):
    def __init__(self, kernel_size=7):
        super().__init__()
        self.conv = nn.Conv2d(2, 1, kernel_size, padding=kernel_size//2, bias=False)
        self.sigmoid = nn.Sigmoid()
    def forward(self, x): return self.sigmoid(self.conv(torch.cat([torch.mean(x, 1, keepdim=True), torch.max(x, 1, keepdim=True)[0]], 1)))

class CBAM(nn.Module):
    def __init__(self, channels):
        super().__init__()
        self.ca, self.sa = ChannelAttention(channels), SpatialAttention()
    def forward(self, x): return self.sa(self.ca(x) * x) * (self.ca(x) * x)

class EfficientNetB5FusionNet(nn.Module):
    def __init__(self, num_classes=7):
        super().__init__()
        self.features = models.efficientnet_b5().features
        self.cbam = CBAM(2048) # B5 depth
        self.global_pool = nn.AdaptiveAvgPool2d(1)
        self.classifier = nn.Sequential(nn.Linear(2048 + 256, 512), nn.BatchNorm1d(512), nn.SiLU(), nn.Dropout(0.4), nn.Linear(512, num_classes))

    def forward(self, img, mlbp):
        return self.classifier(torch.cat([torch.flatten(self.global_pool(self.cbam(self.features(img))), 1), mlbp], dim=1))

