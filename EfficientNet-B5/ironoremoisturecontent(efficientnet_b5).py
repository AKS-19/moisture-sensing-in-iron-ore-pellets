def compute_mlbp(image_cv_gray):
    h, w = image_cv_gray.shape
    img_float = image_cv_gray.astype(np.float32)
    kernel = np.ones((3, 3), np.float32) / 9.0
    mean_tau = cv2.filter2D(img_float, -1, kernel)

    padded = np.pad(img_float, 1, mode='reflect')
    mlbp = np.zeros((h, w), dtype=np.uint8)

    dx = [-1,  0,  1, 1, 1, 0, -1, -1]
    dy = [-1, -1, -1, 0, 1, 1,  1,  0]

    for i in range(8):
        y1, y2 = 1 + dy[i], 1 + dy[i] + h
        x1, x2 = 1 + dx[i], 1 + dx[i] + w
        neighbor = padded[y1:y2, x1:x2]
        mlbp |= ((neighbor >= mean_tau).astype(np.uint8) << i)

    hist, _ = np.histogram(mlbp.ravel(), bins=256, range=(0, 256))
    hist_float = hist.astype(np.float32)
    return hist_float / (hist_float.sum() + 1e-6)

class PelletDataset(Dataset):
    def __init__(self, root_dir, transform=None):
        self.root_dir, self.transform = Path(root_dir), transform
        self.image_paths, self.labels = [], []
        valid_ext = ('.jpg', '.jpeg', '.png', '.bmp', '.tiff', '.webp')

        for idx, cls in enumerate(CLASSES):
            cls_dir = self.root_dir / cls
            if cls_dir.exists():
                for file_name in os.listdir(cls_dir):
                    if file_name.lower().endswith(valid_ext):
                        self.image_paths.append(str(cls_dir / file_name)); self.labels.append(idx)

    def __len__(self): return len(self.image_paths)
    def __getitem__(self, idx):
        image_pil = Image.open(self.image_paths[idx]).convert('RGB')
        img_tensor = self.transform(image_pil)

        img_cv_gray = cv2.resize(cv2.cvtColor(np.array(image_pil), cv2.COLOR_RGB2GRAY), (224, 224))
        mlbp_vec = compute_mlbp(img_cv_gray)
        # Force float32 to prevent PyTorch type mismatch
        mlbp_tensor = torch.tensor(mlbp_vec, dtype=torch.float32)
        return img_tensor, mlbp_tensor, self.labels[idx]

class ChannelAttention(nn.Module):
    def __init__(self, in_planes, ratio=16):
        super().__init__()
        self.avg_pool = nn.AdaptiveAvgPool2d(1)
        self.max_pool = nn.AdaptiveMaxPool2d(1)
        self.mlp = nn.Sequential(nn.Conv2d(in_planes, in_planes // ratio, 1, bias=False), nn.ReLU(), nn.Conv2d(in_planes // ratio, in_planes, 1, bias=False))
        self.sigmoid = nn.Sigmoid()
    def forward(self, x): return self.sigmoid(self.mlp(self.avg_pool(x)) + self.mlp(self.max_pool(x)))

class SpatialAttention(nn.Module):
    def __init__(self, kernel_size=7):
        super().__init__()
        self.conv = nn.Conv2d(2, 1, kernel_size, padding=kernel_size//2, bias=False)
        self.sigmoid = nn.Sigmoid()
    def forward(self, x):
        avg_out = torch.mean(x, dim=1, keepdim=True)
        max_out, _ = torch.max(x, dim=1, keepdim=True)
        return self.sigmoid(self.conv(torch.cat([avg_out, max_out], dim=1)))

class CBAM(nn.Module):
    def __init__(self, channels):
        super().__init__()
        self.ca, self.sa = ChannelAttention(channels), SpatialAttention()
    def forward(self, x):
        x = self.ca(x) * x
        return self.sa(x) * x

class EfficientNetB5FusionNet(nn.Module):
    def __init__(self, num_classes=7):
        super().__init__()
        # B5 Outputs 2048 Channels natively
        self.features = models.efficientnet_b5(weights=models.EfficientNet_B5_Weights.IMAGENET1K_V1).features
        self.cbam = CBAM(2048)
        self.global_pool = nn.AdaptiveAvgPool2d(1)

        # 2048 (Global) + 256 (Local MLBP) = 2304 Total Features
        self.classifier = nn.Sequential(
            nn.Linear(2048 + 256, 512),
            nn.BatchNorm1d(512),
            nn.SiLU(),
            nn.Dropout(0.4),
            nn.Linear(512, num_classes)
        )

    def forward(self, img, mlbp):
        f_global = torch.flatten(self.global_pool(self.cbam(self.features(img))), 1)
        return self.classifier(torch.cat([f_global, mlbp], dim=1))

