def train_and_evaluate():
    prepare_dataset_hierarchy()
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"\n[INFO] Accelerating computation on: {device}")

    train_data = PelletDataset(os.path.join(SPLIT_DIR, 'train'), transform=train_transforms)
    val_data = PelletDataset(os.path.join(SPLIT_DIR, 'val'), transform=test_transforms)
    test_data = PelletDataset(os.path.join(SPLIT_DIR, 'test'), transform=test_transforms)

    # STRICT Batch Size Limit: 16 to prevent B5 from OOM crashing
    batch_size = 16
    train_loader = DataLoader(train_data, batch_size=batch_size, shuffle=True, num_workers=2)
    val_loader = DataLoader(val_data, batch_size=batch_size, shuffle=False, num_workers=2)
    test_loader = DataLoader(test_data, batch_size=batch_size, shuffle=False)

    model = EfficientNetB5FusionNet(num_classes=len(CLASSES)).to(device)
    criterion = nn.CrossEntropyLoss()
    optimizer = optim.AdamW(model.parameters(), lr=1e-4, weight_decay=1e-2)
    scheduler = optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode='min', factor=0.1, patience=3)

    epochs = 30
    best_val_loss = float('inf')

    print("\n[INFO] Initializing EfficientNet-B5 Dual-Stream Training...")

    for epoch in range(epochs):
        model.train()
        train_loss = 0.0
        for imgs, mlbps, labels in train_loader:
            imgs, mlbps, labels = imgs.to(device), mlbps.to(device), labels.to(device)
            optimizer.zero_grad()
            loss = criterion(model(imgs, mlbps), labels)
            loss.backward()
            optimizer.step()
            train_loss += loss.item() * imgs.size(0)

        train_loss /= len(train_loader.dataset)

        model.eval()
        val_loss, all_preds, all_labels = 0.0, [], []
        with torch.no_grad():
            for imgs, mlbps, labels in val_loader:
                imgs, mlbps, labels = imgs.to(device), mlbps.to(device), labels.to(device)
                outputs = model(imgs, mlbps)
                loss = criterion(outputs, labels)
                val_loss += loss.item() * imgs.size(0)

                _, preds = torch.max(outputs, 1)
                all_preds.extend(preds.cpu().numpy()); all_labels.extend(labels.cpu().numpy())

        val_loss /= len(val_loader.dataset)
        scheduler.step(val_loss)
        print(f"Epoch [{epoch+1}/{epochs}] | Train Loss: {train_loss:.4f} | Val Loss: {val_loss:.4f} | Val Acc: {accuracy_score(all_labels, all_preds):.4f}")

        if val_loss < best_val_loss:
            best_val_loss = val_loss
            torch.save(model.state_dict(), 'best_effnet_b5.pt')

    print("\n[INFO] Training Complete. Best model saved as 'best_effnet_b5.pt'")
    if IN_COLAB: files.download('best_effnet_b5.pt')

    # EVALUATION
    model.load_state_dict(torch.load('best_effnet_b5.pt', map_location=device, weights_only=True))
    model.eval()
    all_preds, all_labels = [], []
    print("\n[INFO] Evaluating on Test Split...")

    with torch.no_grad():
        for imgs, mlbps, labels in test_loader:
            imgs, mlbps, labels = imgs.to(device), mlbps.to(device), labels.to(device)
            _, preds = torch.max(model(imgs, mlbps), 1)
            all_preds.extend(preds.cpu().numpy()); all_labels.extend(labels.cpu().numpy())

    print("\n--- Classification Report (EfficientNet-B5) ---")
    print(classification_report(all_labels, all_preds, target_names=CLASSES, zero_division=0))

    plt.figure(figsize=(8, 6))
    sns.heatmap(confusion_matrix(all_labels, all_preds), annot=True, fmt='d', cmap='Blues', xticklabels=CLASSES, yticklabels=CLASSES)
    plt.title('EfficientNet-B5 Moisture Content - Confusion Matrix')
    plt.xlabel('Predicted Label'); plt.ylabel('True Label'); plt.tight_layout()
    plt.show()

if __name__ == "__main__":
    train_and_evaluate()

