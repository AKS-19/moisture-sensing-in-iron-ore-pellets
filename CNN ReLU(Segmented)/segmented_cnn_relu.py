import os, torch, io, matplotlib.pyplot as plt, numpy as np
import torch.nn as nn
from PIL import Image
from torchvision import transforms
from google.colab import files

CLASSES = ['10gm', '30gm', '40gm', '50gm', '60gm', '70gm', '80gm']

class QuadrantCNN(nn.Module):
    def __init__(self, num_classes=7):
        super().__init__()
        self.layer1 = nn.Sequential(nn.Conv2d(3, 32, 3, padding='same'), nn.BatchNorm2d(32), nn.ReLU(), nn.MaxPool2d(2))
        self.layer2 = nn.Sequential(nn.Conv2d(32, 64, 3, padding='same'), nn.BatchNorm2d(64), nn.ReLU(), nn.MaxPool2d(2))
        self.layer3 = nn.Sequential(nn.Conv2d(64, 128, 3, padding='same'), nn.BatchNorm2d(128), nn.ReLU(), nn.MaxPool2d(2))
        self.layer4 = nn.Sequential(nn.Conv2d(128, 256, 3, padding='same'), nn.BatchNorm2d(256), nn.ReLU(), nn.AdaptiveAvgPool2d((2, 2)))
        self.flatten = nn.Flatten()
        self.fc = nn.Sequential(nn.Linear(256 * 2 * 2, 512), nn.BatchNorm1d(512), nn.ReLU(), nn.Dropout(0.4), nn.Linear(512, num_classes))

    def forward(self, x): return self.fc(self.flatten(self.layer4(self.layer3(self.layer2(self.layer1(x))))))

def predict_quadrant_ensemble():
    if not os.path.exists('best_quadrant_cnn.pt'):
        print("[ERROR] 'best_quadrant_cnn.pt' not found!"); return

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = QuadrantCNN(len(CLASSES)).to(device)
    model.load_state_dict(torch.load('best_quadrant_cnn.pt', map_location=device, weights_only=True))
    model.eval()

    tf = transforms.Compose([transforms.ToTensor(), transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])])

    print("\n[READY] Please upload a full-size iron ore pellet image.")
    uploaded = files.upload()

    for filename, file_data in uploaded.items():
        original_img = Image.open(io.BytesIO(file_data)).convert('RGB')

        # 1. Resize and Crop into 4 Pieces
        img_resized = original_img.resize((656, 480))
        quads = [
            img_resized.crop((0, 0, 328, 240)), img_resized.crop((328, 0, 656, 240)),
            img_resized.crop((0, 240, 328, 480)), img_resized.crop((328, 240, 656, 480))
        ]

        # 2. Batch them together: shape becomes [4, 3, 240, 328]
        batch_tensors = torch.stack([tf(q) for q in quads]).to(device)

        with torch.no_grad():
            raw_logits = model(batch_tensors) # Run inference on all 4 simultaneously!

            # Apply Softmax to all 4 quadrants individually
            quad_probs = nn.Softmax(dim=1)(raw_logits)

            # Ensemble: Average the probabilities across the 4 quadrants
            final_probs = torch.mean(quad_probs, dim=0)

            conf, pred_idx = torch.max(final_probs, 0)

        plt.figure(figsize=(6, 6))
        plt.imshow(original_img)
        plt.title(f"Ensemble Prediction: {CLASSES[pred_idx.item()]}\n(Average Softmax Confidence: {conf.item() * 100:.2f}%)", color='blue', fontweight='bold')
        plt.axis('off'); plt.show()

        print("\n--- Final Ensemble Output (Average of 4 Quadrants) ---")
        for i, c in enumerate(CLASSES): print(f"{c}: {final_probs[i].item() * 100:.2f}%")

predict_quadrant_ensemble()

