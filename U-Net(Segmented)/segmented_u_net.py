def train_and_evaluate():
    prepare_quadrant_dataset()
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"\n[INFO] Fast U-Net Training Initialized on: {device}")

    tr_loader = DataLoader(QuadrantDataset(os.path.join(SPLIT_DIR, 'train'), train_tf), batch_size=32, shuffle=True, pin_memory=True, num_workers=2)
    val_loader = DataLoader(QuadrantDataset(os.path.join(SPLIT_DIR, 'val'), test_tf), batch_size=32, pin_memory=True, num_workers=2)
    te_loader = DataLoader(QuadrantDataset(os.path.join(SPLIT_DIR, 'test'), test_tf), batch_size=32)

    model = FastQuadrantUNet(len(CLASSES)).to(device)
    criterion = nn.CrossEntropyLoss()
    optimizer = optim.AdamW(model.parameters(), lr=1e-3, weight_decay=1e-4)
    scheduler = optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode='min', factor=0.1, patience=2)
    scaler = GradScaler()

    best_val_loss = float('inf')
    epochs = 30
    patience_counter = 0
    patience_limit = 5

    # Tracking lists for our plots
    history_train_loss, history_val_loss = [], []
    history_train_acc, history_val_acc = [], []

    for epoch in range(epochs):
        # --- TRAINING PHASE ---
        model.train()
        tr_loss = 0.0
        train_preds, train_labels = [], []

        for imgs, lbls in tr_loader:
            imgs, lbls = imgs.to(device, non_blocking=True), lbls.to(device, non_blocking=True)
            optimizer.zero_grad()

            with autocast():
                out = model(imgs)
                loss = criterion(out, lbls)

            scaler.scale(loss).backward()
            scaler.step(optimizer)
            scaler.update()

            tr_loss += loss.item() * imgs.size(0)

            # Track Training Accuracy dynamically
            _, preds = torch.max(out, 1)
            train_preds.extend(preds.detach().cpu().numpy())
            train_labels.extend(lbls.detach().cpu().numpy())

        tr_loss /= len(tr_loader.dataset)
        tr_acc = accuracy_score(train_labels, train_preds)

        # --- VALIDATION PHASE ---
        model.eval()
        val_loss, all_preds, all_labels = 0.0, [], []
        with torch.no_grad():
            for imgs, lbls in val_loader:
                imgs, lbls = imgs.to(device), lbls.to(device)
                with autocast():
                    out = model(imgs)
                    loss = criterion(out, lbls)
                val_loss += loss.item() * imgs.size(0)
                all_preds.extend(torch.max(out, 1)[1].cpu().numpy()); all_labels.extend(lbls.cpu().numpy())

        val_loss /= len(val_loader.dataset)
        val_acc = accuracy_score(all_labels, all_preds)
        scheduler.step(val_loss)

        print(f"Epoch [{epoch+1}/{epochs}] | Train Loss: {tr_loss:.4f} - Train Acc: {tr_acc:.4f} | Val Loss: {val_loss:.4f} - Val Acc: {val_acc:.4f}")

        # Append to histories
        history_train_loss.append(tr_loss); history_val_loss.append(val_loss)
        history_train_acc.append(tr_acc); history_val_acc.append(val_acc)

        # Early Stopping
        if val_loss < best_val_loss:
            best_val_loss = val_loss
            patience_counter = 0
            torch.save(model.state_dict(), 'best_fast_unet.pt')
        else:
            patience_counter += 1
            if patience_counter >= patience_limit:
                print(f"\n[INFO] Early Stopping Triggered! Validation loss stopped improving.")
                break

    # ==========================================================
    # VISUALIZATION PLOTS
    # ==========================================================

    # 1. Plot: Training vs Validation Loss
    plt.figure(figsize=(10, 5))
    plt.plot(range(1, len(history_train_loss)+1), history_train_loss, label='Training Loss', marker='o', color='royalblue')
    plt.plot(range(1, len(history_val_loss)+1), history_val_loss, label='Validation Loss', marker='s', color='darkorange')
    plt.title('Training Loss vs Validation Loss (Fast U-Net)', fontsize=14, fontweight='bold')
    plt.xlabel('Epochs', fontsize=12); plt.ylabel('Cross-Entropy Loss', fontsize=12)
    plt.legend(fontsize=12); plt.grid(True, linestyle='--', alpha=0.7); plt.tight_layout()
    plt.show()

    # 2. Plot: Training vs Validation Accuracy
    plt.figure(figsize=(10, 5))
    plt.plot(range(1, len(history_train_acc)+1), history_train_acc, label='Training Accuracy', marker='o', color='forestgreen')
    plt.plot(range(1, len(history_val_acc)+1), history_val_acc, label='Validation Accuracy', marker='s', color='mediumorchid')
    plt.title('Training Accuracy vs Validation Accuracy (Fast U-Net)', fontsize=14, fontweight='bold')
    plt.xlabel('Epochs', fontsize=12); plt.ylabel('Accuracy', fontsize=12)
    plt.legend(fontsize=12); plt.grid(True, linestyle='--', alpha=0.7); plt.tight_layout()
    plt.show()

    # Evaluation on Test Split
    print("\n[INFO] Evaluating on 328x240 Test Quadrants...")
    model.load_state_dict(torch.load('best_fast_unet.pt', map_location=device, weights_only=True))
    model.eval()
    test_preds, test_labels = [], []
    with torch.no_grad():
        for imgs, lbls in te_loader:
            test_preds.extend(torch.max(model(imgs.to(device)), 1)[1].cpu().numpy()); test_labels.extend(lbls.numpy())

    print("\n--- Classification Report (Fast U-Net) ---")
    print(classification_report(test_labels, test_preds, target_names=CLASSES, zero_division=0))

    # 3. Plot: Confusion Matrix
    cm = confusion_matrix(test_labels, test_preds)
    plt.figure(figsize=(8, 6))
    sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', xticklabels=CLASSES, yticklabels=CLASSES)
    plt.title('Fast U-Net - Confusion Matrix', fontsize=14, fontweight='bold')
    plt.xlabel('Predicted Label', fontsize=12); plt.ylabel('True Label', fontsize=12)
    plt.tight_layout(); plt.show()

    if IN_COLAB: files.download('best_fast_unet.pt')

if __name__ == "__main__":
    train_and_evaluate()

