ZIP_PATH, BASE_DIR, SPLIT_DIR = "iron_ore_pellets.zip", "dataset_raw", "dataset_quad_unet"
CLASSES = ['10gm', '30gm', '40gm', '50gm', '60gm', '70gm', '80gm']

