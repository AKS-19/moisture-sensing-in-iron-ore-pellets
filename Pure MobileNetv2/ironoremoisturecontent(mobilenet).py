    model = PureMobileNet(len(CLASSES)).to(device)
    model.load_state_dict(torch.load('best_pure_mobilenet.pt', map_location=device, weights_only=True))
    model.eval()

    tf = transforms.Compose([
        transforms.Resize((224, 224)),
        transforms.ToTensor(),
        transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])
    ])

    print("\n[READY] Please upload a full-size iron ore pellet image.")
    uploaded = files.upload()

    for filename, file_data in uploaded.items():
        original_img = Image.open(io.BytesIO(file_data)).convert('RGB')
        img_tensor = tf(original_img).unsqueeze(0).to(device)

        with torch.no_grad():
            from torch.cuda.amp import autocast
            with autocast():
                raw_logits = model(img_tensor)
                probabilities = nn.Softmax(dim=1)(raw_logits)[0]

            conf, pred_idx = torch.max(probabilities, 0)

        plt.figure(figsize=(6, 6))
        plt.imshow(original_img)
        plt.title(f"MobileNet Prediction: {CLASSES[pred_idx.item()]}\n(Softmax Confidence: {conf.item() * 100:.2f}%)", color='purple', fontweight='bold')
        plt.axis('off'); plt.show()

        print("\n--- Final Output ---")
        for i, c in enumerate(CLASSES): print(f"{c}: {probabilities[i].item() * 100:.2f}%")

