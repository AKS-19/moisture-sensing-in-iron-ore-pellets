def benchmark_mobilenet(iterations=1000):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"[INFO] Benchmarking MobileNet Pipeline on: {device.type.upper()}")

    if not os.path.exists('best_pure_mobilenet.pt'):
        print("[ERROR] 'best_pure_mobilenet.pt' not found."); return

    model = PureMobileNet(len(CLASSES)).to(device)
    model.load_state_dict(torch.load('best_pure_mobilenet.pt', map_location=device, weights_only=True))
    model.eval()

    tf = transforms.Compose([
        transforms.Resize((224, 224)),
        transforms.ToTensor(),
        transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])
    ])

    dummy_image = Image.fromarray(np.random.randint(0, 255, (494, 659, 3), dtype=np.uint8))

    print("[INFO] Warming up GPU with Mixed Precision...")
    for _ in range(50):
        dummy_tensor = tf(dummy_image).unsqueeze(0).to(device)
        with torch.no_grad():
            with autocast(): _ = model(dummy_tensor)

    print(f"[INFO] Running {iterations} iterations on MobileNet Pipeline...\n")

    pipeline_times = []
    with torch.no_grad():
        for _ in range(iterations):
            if device.type == 'cuda': torch.cuda.synchronize()
            t_start = time.perf_counter()

            img_tensor = tf(dummy_image).unsqueeze(0).to(device)

            with autocast():
                probs = nn.Softmax(dim=1)(model(img_tensor))

            if device.type == 'cuda': torch.cuda.synchronize()
            pipeline_times.append((time.perf_counter() - t_start) * 1000)

    avg_pipe_time = np.mean(pipeline_times)

    print("="*60)
    print("         PURE MOBILENET SPEED REPORT")
    print("="*60)
    print(f"Full Pipeline Latency : {avg_pipe_time:.2f} ms / frame")
    print(f"Actual Production FPS : {1000/avg_pipe_time:.1f} FPS")
    print("="*60)

benchmark_mobilenet()